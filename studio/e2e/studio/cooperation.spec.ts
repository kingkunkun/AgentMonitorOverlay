import { expect, test } from "@playwright/test";
import { join } from "node:path";
import { RelayStore, startRelayServer } from "@amo-studio/relay";
import type { CooperationState } from "@amo-studio/protocol";
import { launchStudio, screenshot } from "../support/studio.js";

test("team and phone remotes have independent accounts, toggles and local account management", async () => {
  const studio = await launchStudio();
  const db = new RelayStore(join(studio.root, "test-team.db"));
  const team = await startRelayServer({ store: db, host: "127.0.0.1", port: 0 });
  db.register("合作测试", "team-password-123");
  try {
    const { page, app } = studio;
    await expect(page.getByTestId("topbar-marks")).toHaveCount(0);
    await page.getByTestId("cooperation-open").click();
    const dialog = page.getByRole("dialog", { name: "合作模式", exact: true });
    expect((await studio.api<CooperationState>("GET", "/api/cooperation")).server.running).toBe(false);
    await dialog.getByLabel("允许同一局域网的手机连接", { exact: true }).click();
    await expect(dialog.getByLabel("允许同一局域网的手机连接", { exact: true })).toBeChecked();
    expect((await studio.api<CooperationState>("GET", "/api/cooperation")).server).toMatchObject({ running: false, lan: true });
    await dialog.getByLabel("允许同一局域网的手机连接", { exact: true }).click();
    await expect(dialog.getByLabel("允许同一局域网的手机连接", { exact: true })).not.toBeChecked();
    await dialog.getByRole("textbox", { name: "服务器地址", exact: true }).fill(team.url);
    await dialog.getByRole("textbox", { name: "账号", exact: true }).fill("合作测试");
    await dialog.getByLabel("密码", { exact: true }).fill("team-password-123");
    await dialog.getByRole("button", { name: "登录账号", exact: true }).click();
    await expect(dialog.getByRole("button", { name: "退出团队账号并关闭团队远程、中转", exact: true })).toBeVisible();
    await dialog.getByLabel("手机账号名称", { exact: true }).fill("合作测试");
    await dialog.getByLabel("手机账号密码", { exact: true }).fill("phone-password-123");
    await dialog.getByTestId("phone-remote-settings").getByLabel("同步团队来信", { exact: true }).check();
    await dialog.getByRole("button", { name: "创建手机账号", exact: true }).click();
    const row = dialog.getByTestId("phone-account-row");
    await expect(row).toContainText("合作测试");
    await dialog.getByTestId("phone-remote-toggle").click();
    await expect(dialog.getByTestId("phone-remote-toggle")).toHaveText("关闭手机远程");
    await dialog.getByTestId("cooperation-remote-toggle").click();
    await expect(dialog.getByTestId("cooperation-remote-toggle")).toHaveText("关闭远程");
    await dialog.getByTestId("cooperation-remote-toggle").click();
    const state = await studio.api<CooperationState>("GET", "/api/cooperation");
    expect(state).toMatchObject({ account: { name: "合作测试", server: team.url }, remoteEnabled: false, server: { running: true, accounts: [expect.objectContaining({ name: "合作测试", forwardTeamInbox: true })] } });
    await screenshot(app, "studio", "independent-phone-remote", page);
    await row.getByRole("button", { name: "重设密码", exact: true }).click();
    await row.getByLabel("合作测试 的新密码", { exact: true }).fill("phone-new-password-123");
    await row.getByRole("button", { name: "保存新密码并断开旧登录", exact: true }).click();
    await row.getByRole("button", { name: "停用账号", exact: true }).click();
    await expect(row).toContainText("已停用");
    await row.getByRole("button", { name: "启用账号", exact: true }).click();
    await expect(row).toContainText("可登录");
    await dialog.getByTestId("cooperation-off").click();
    await expect(dialog.getByRole("button", { name: "登录账号", exact: true })).toBeVisible();
    expect(await studio.api<CooperationState>("GET", "/api/cooperation")).toMatchObject({ account: null, remoteEnabled: false, server: { running: false, accounts: [expect.objectContaining({ name: "合作测试" })] } });
    await row.getByRole("button", { name: "删除账号", exact: true }).click();
    await row.getByRole("button", { name: "确认删除", exact: true }).click();
    await expect(row).toHaveCount(0);
    await screenshot(app, "studio", "phone-remote-off", page);
  } finally { await team.close(); db.close(); await studio.close(); }
});
