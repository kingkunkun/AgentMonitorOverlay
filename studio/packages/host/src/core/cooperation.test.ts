import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { readCooperation, type Protector } from "@amo-studio/account";
import { removeTempDir } from "@amo-studio/testkit";
import { HostService } from "../service.js";
import { Store } from "../store/store.js";
import { CodexRuntime } from "../runtime/codex/codex-runtime.js";
import { FakeServers } from "../runtime/codex/fake-servers.test-support.js";
import { Cooperation } from "./cooperation.js";
import { RelayStore, startRelayServer } from "@amo-studio/relay";

const clean: Array<() => Promise<void>> = [];
afterEach(async () => { for (const run of clean.splice(0).reverse()) await run(); });
async function setup() {
  const root = mkdtempSync(join(tmpdir(), "amo-cooperation-"));
  const env = { AMO_HOME: join(root, "amo") };
  const protector: Protector = { protect: async (x) => Buffer.from(x).toString("base64"), unprotect: async (x) => Buffer.from(x, "base64").toString() };
  const store = new Store(join(root, "data/studio.db"));
  const profiles = [{ id: "p", label: "P", runtime: "codex" as const, provider: "x", model: "m" }];
  const servers = new FakeServers(profiles);
  const service = new HostService(store, new CodexRuntime({ store, servers, profiles }), profiles);
  service.teamLink.start({ env, protector });
  service.remote.start({ env, protector });
  await service.teamLink.settled();
  const cooperation = new Cooperation(service, 0);
  clean.push(async () => { await cooperation.stop(); service.teamRelay.stop(); service.remote.stop(); service.teamLink.stop(); await servers.close(); store.close(); removeTempDir(root); });
  return { cooperation, service, env, root };
}
async function teamServer(cooperation: Cooperation, name: string) {
  const dir = mkdtempSync(join(tmpdir(), "amo-coop-team-"));
  const db = new RelayStore(join(dir, "team.db"));
  const server = await startRelayServer({ store: db, host: "127.0.0.1", port: 0 });
  clean.push(async () => { await server.close(); db.close(); removeTempDir(dir); });
  const created = db.register(name, "long-password-123"); db.logout(created.key);
  return cooperation.account({ action: "login", server: server.url, name, password: "long-password-123" });
}
it("team login stays independent from local phone accounts; off signs out and stops both connection domains", async () => {
  const { cooperation, service, env } = await setup();
  await teamServer(cooperation, "team-user");
  const state = await cooperation.setServer(true);
  const denied = await fetch(state.server.addresses[0]! + "/api/register", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "phone", password: "long-password-123" }) });
  expect(denied.status).toBe(403);
  expect(() => cooperation.createPhoneAccount({ name: "phone", password: "short" })).toThrow("12");
  const signed = cooperation.createPhoneAccount({ name: "phone", password: "phone-password-123" });
  expect(signed.account?.name).toBe("team-user");
  expect(signed.remoteEnabled).toBe(false);
  cooperation.relay(true);
  expect(readCooperation(env).relayEnabled).toBe(true);
  const off = await cooperation.off();
  expect(off).toMatchObject({ account: null, relayEnabled: false, remoteEnabled: false, server: { running: false, accounts: [expect.objectContaining({ name: "phone" })] } });
  expect(service.teamLink.account).toBeNull();
  expect(readCooperation(env)).toMatchObject({ relayEnabled: false, serverEnabled: false });
});
it("file export needs a fresh local approval and refuses native private stores before creating a request", async () => {
  const { cooperation, root } = await setup();
  await expect(cooperation.confirmTransfer("t", "peer", join(root, ".codex/sessions/private.jsonl"))).rejects.toThrow("禁止");
  expect(cooperation.state().transfers).toEqual([]);
  const rejected = cooperation.confirmTransfer("t", "peer", join(root, "project/file.txt"));
  const request = cooperation.state().transfers[0]!;
  cooperation.answer(request.id, false);
  await expect(rejected).rejects.toThrow("未确认");
  const allowed = cooperation.confirmTransfer("t", "peer", join(root, "project/file.txt"));
  cooperation.answer(cooperation.state().transfers[0]!.id, true);
  await allowed;
  await expect(cooperation.confirmTransfer("t", "peer", join(root, "project/file.txt"), 100)).resolves.toBeUndefined();
  await expect(cooperation.confirmTransfer("t", "other-peer", join(root, "project/file.txt"), 100)).rejects.toThrow("尚未");
});
it("external native conversations cannot be listed, previewed or imported and auto-send remains off", async () => {
  const { service } = await setup();
  expect(await service.tasks.outsideSessions()).toMatchObject({ sessions: [], unavailable: expect.stringContaining("隐私") });
  await expect(service.tasks.outsidePreview("native-id")).rejects.toThrow("隐私");
  service.config.updateSettings({ teamAutoSend: true });
  expect(service.config.settings().teamAutoSend).toBe(false);
});
it("all-task sync applies only to an explicitly paired own-account device, and imported tasks stay private", async () => {
  const { cooperation, service } = await setup();
  await teamServer(cooperation, "owner");
  service.store.setKv("remote.pairs", JSON.stringify([{ account: "owner", device: "phone", name: "自己的手机", role: "owner", pairedAt: new Date().toISOString() }, { account: "other", device: "other", name: "其他人的设备", role: "owner", pairedAt: new Date().toISOString() }]));
  await service.remote.setEnabled(true);
  const { task } = await service.tasks.createTask({ title: "本地任务" });
  const { task: imported } = await service.tasks.createTask({ title: "过去导入的对话" });
  const s = service.store.createSession({ taskId: imported.id, topicId: null, parentId: null, kind: "main", runtime: "codex", profileId: "p", workspaceId: imported.workspaceId, title: "", status: "idle", writer: "workbench", runtimeRef: null });
  service.store.setKv("claude-adopted:outside", s.id);
  cooperation.syncOwn(true);
  expect(service.remote.grants.list()).toEqual([expect.objectContaining({ taskId: task.id, account: "owner", device: "phone" })]);
  expect(cooperation.taskAllowed(imported.id)).toBe(false);
  const session = service.store.createSession({ taskId: task.id, topicId: null, parentId: null, kind: "main", runtime: "codex", profileId: "p", workspaceId: task.workspaceId, title: "", status: "idle", writer: "workbench", runtimeRef: null });
  service.remote.grants.grant(task.id, { account: "other", device: "other" });
  const build = vi.spyOn(service.buildJob, "command").mockResolvedValue({ mode: "start" });
  expect((await service.remote.grants.serve({ account: "other", device: "other" }, "rt.send", { sessionId: session.id, text: "/打包" })).kind).toBe("error");
  expect(build).not.toHaveBeenCalled();
  expect((await service.remote.grants.serve({ account: "owner", device: "phone" }, "rt.send", { sessionId: session.id, text: "/打包" })).kind).not.toBe("error");
  expect(build).toHaveBeenCalledWith(session.id, "/打包");
  expect((await service.remote.grants.serve({ account: "other", device: "other" }, "rt.presets", { sessionId: session.id })).kind).toBe("error");
  const presets = await service.remote.grants.serve({ account: "owner", device: "phone" }, "rt.presets", { sessionId: session.id });
  expect(presets.body).toMatchObject({ presets: [expect.objectContaining({ job: "ios" }), expect.objectContaining({ job: "android" })] });
  expect(JSON.stringify(presets.body)).not.toContain("filePath");
  const archive = vi.spyOn(service.tasks, "archiveTask").mockResolvedValue(task);
  expect((await service.remote.grants.serve({ account: "other", device: "other" }, "rt.task-archive", { taskId: task.id })).kind).toBe("error");
  expect(archive).not.toHaveBeenCalled();
  expect((await service.remote.grants.serve({ account: "owner", device: "phone" }, "rt.task-archive", { taskId: task.id })).kind).not.toBe("error");
  expect(archive).toHaveBeenCalledWith(task.id);
  const continuation = vi.spyOn(service.sessions, "continueWithModel").mockResolvedValue(session);
  expect((await service.remote.grants.serve({ account: "other", device: "other" }, "rt.continue", { sessionId: session.id, profileId: "p" })).kind).toBe("error");
  expect((await service.remote.grants.serve({ account: "owner", device: "phone" }, "rt.continue", { sessionId: session.id, profileId: "ungranted-profile" })).kind).toBe("error");
  expect(continuation).not.toHaveBeenCalled();
  expect((await service.remote.grants.serve({ account: "owner", device: "phone" }, "rt.continue", { sessionId: session.id, profileId: "p" })).kind).not.toBe("error");
  expect(continuation).toHaveBeenCalledWith(session.id, "p", undefined);
  expect((await service.remote.grants.serve({ account: "other", device: "other" }, "rt.choices", { sessionId: session.id, all: true })).kind).toBe("error");
  await cooperation.off();
});
